/** Числа словами для озвучення (без залежностей, щоб можна було тестувати й використовувати будь-де). */
export type Gender = 'm' | 'f' | 'n';
const UNITS = ['нуль', '', '', 'три', 'чотири', 'п’ять', 'шість', 'сім', 'вісім', 'дев’ять', 'десять', 'одинадцять', 'дванадцять',
  'тринадцять', 'чотирнадцять', 'п’ятнадцять', 'шістнадцять', 'сімнадцять', 'вісімнадцять', 'дев’ятнадцять'];
const TENS = ['', '', 'двадцять', 'тридцять', 'сорок', 'п’ятдесят', 'шістдесят', 'сімдесят', 'вісімдесят', 'дев’яносто'];

/** Число словами (0…99) з узгодженням роду: одна кулька, одне яблуко, дві мушлі. */
export function numberWords(n: number, gender: Gender = 'm'): string {
  if (!Number.isInteger(n) || n < 0 || n > 99) return String(n);
  if (n === 1) return gender === 'f' ? 'одна' : gender === 'n' ? 'одне' : 'один';
  if (n === 2) return gender === 'f' ? 'дві' : 'два';
  if (n < 20) return UNITS[n];
  const t = Math.floor(n / 10), u = n % 10;
  return u ? `${TENS[t]} ${numberWords(u, gender)}` : TENS[t];
}

/** Рід за формою однини: кулька/мушля → жіночий, яблуко/яйце → середній, решта → чоловічий. */
export const genderOf = (singular: string): Gender => /[ая]$/.test(singular) ? 'f' : /[оеє]$/.test(singular) ? 'n' : 'm';

