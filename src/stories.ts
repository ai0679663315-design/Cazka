/** Наступна пригода: спершу незавершені за інтересом, потім будь-які незавершені, потім по колу. */
export function nextStory(interest: string, completedIds: string[], totalCompleted = 0): Story {
  const fresh = STORIES.filter(s => !completedIds.includes(s.id));
  return fresh.find(s => s.interest === interest) ?? fresh[0] ?? STORIES[totalCompleted % STORIES.length];
}

export const storyById = (id: string) => STORIES.find(s => s.id === id) ?? STORIES[0];
